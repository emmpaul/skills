"""Unit tests for scripts/wcag.py. Offline: they generate from scripts/fixtures/.

Run: python3 -m unittest scripts/test_wcag.py
"""

import contextlib
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "wcag.py"
MINI = HERE / "fixtures" / "wcag-mini.json"
BAD = HERE / "fixtures" / "wcag-bad.json"

sys.path.insert(0, str(HERE))
import wcag  # noqa: E402


def run(*args):
    return subprocess.run([sys.executable, str(SCRIPT), *map(str, args)],
                          capture_output=True, text=True)


def snapshot(root):
    return {p.relative_to(root).as_posix(): p.read_bytes()
            for p in sorted(Path(root).rglob("*")) if p.is_file()}


def mini():
    return json.loads(MINI.read_text())


def criteria(data):
    return data["principles"][0]["guidelines"][0]["successcriteria"]


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.refs = self.tmp / "references"
        self.out = self.refs / "wcag"

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def update(self, source=MINI, *extra, out=None):
        return run("update", "--source", source, "--out", out or self.out, *extra)

    def check(self):
        return run("check", "--out", self.out)

    def generate(self):
        r = self.update()
        self.assertEqual(r.returncode, 0, r.stderr)

    def write_source(self, data, name="edited.json"):
        p = self.tmp / name
        p.write_text(json.dumps(data))
        return p

    def sc(self, name="sc/4.1.2-name-role-value.md"):
        return (self.out / name).read_text()


class UpdateTest(Base):
    def test_fixture_produces_expected_files_and_headers(self):
        self.generate()
        self.assertEqual(sorted(snapshot(self.out)), [
            "index.md", "manifest.json", "sc/4.1.1-parsing.md", "sc/4.1.2-name-role-value.md"])
        sc = self.sc()
        lines = sc.splitlines()
        self.assertEqual(lines[0], "<!-- GENERATED by scripts/wcag.py from local file "
                                   "wcag-mini.json. Do not edit; run scripts/wcag.py update. -->")
        self.assertEqual(lines[2], "# 4.1.2 Name, Role, Value (Level A)")
        self.assertIn("- Versions: 2.0, 2.1, 2.2", sc)
        self.assertIn("https://www.w3.org/WAI/WCAG22/Understanding/name-role-value.html", sc)
        self.assertNotIn("\r", sc)

        obs = self.sc("sc/4.1.1-parsing.md")
        self.assertIn("(Level none)", obs)
        self.assertIn("**Obsolete**", obs)

        idx = (self.out / "index.md").read_text()
        self.assertIn("| 4.1.2 | Name, Role, Value | A | 2.0, 2.1, 2.2 |  | "
                      "[sc/4.1.2-name-role-value.md](sc/4.1.2-name-role-value.md) |", idx)
        self.assertIn("| 4.1.1 | Parsing (Obsolete and removed) | - | 2.0, 2.1 | yes |", idx)
        self.assertIn("Counts: A 1, AA 0, AAA 0, obsolete 1.", idx)
        self.assertIn("document-license-2023", idx)

        m = json.loads((self.out / "manifest.json").read_text())
        self.assertEqual(m["wcag_version"], "2.2")
        self.assertEqual(m["source"], "local file wcag-mini.json")
        self.assertEqual(m["counts"], {"A": 1, "AA": 0, "AAA": 0, "obsolete": 1})
        self.assertEqual(m["source_sha256"], wcag.sha256(MINI.read_bytes()))
        self.assertEqual(set(m["files"]), {"index.md", "sc/4.1.1-parsing.md",
                                           "sc/4.1.2-name-role-value.md"})
        for rel, digest in m["files"].items():
            self.assertEqual(wcag.sha256((self.out / rel).read_bytes()), digest)

    def test_local_source_path_not_recorded(self):
        self.generate()
        for body in snapshot(self.out).values():
            self.assertNotIn(str(HERE).encode(), body)

    def test_html_conversion(self):
        self.generate()
        sc = self.sc()
        # relative definition links become absolute; inline formatting kept
        self.assertIn("[name](https://www.w3.org/TR/WCAG22/#dfn-name)", sc)
        self.assertIn("- form elements\n- links and *components generated by scripts*", sc)
        self.assertIn("> **Note:** This success criterion is primarily", sc)
        self.assertIn("1. first **step**\n2. second\n   line", sc)
        self.assertIn("- **Controls**\n\n  Has a `name`.\n\n- **Media**", sc)
        # details already in content are not repeated; details-only text is added
        self.assertEqual(sc.count("form elements"), 1)
        self.assertIn("Details-only paragraph that the content does not repeat.", sc)

    def test_technique_rendering(self):
        self.generate()
        sc = self.sc()
        self.assertIn("## Sufficient techniques\n\nFirst note paragraph.\n\n"
                      "Second note paragraph.\n\n", sc)
        self.assertIn("  - ARIA14: Using aria-label", sc)
        self.assertIn("  - G108: Using markup features to expose the name and role using one "
                      "of the following:\n    - H91: Using HTML form controls and links", sc)
        # `and` plus `using`: the alternatives stay grouped under the `and` set
        self.assertIn("- All of:\n  - G91: Providing link text\n  - semantically indicating links\n"
                      "  - Using one of:\n    - PDF11: Providing links in PDF\n"
                      "    - PDF13: Providing replacement text in PDF", sc)
        self.assertIn("- Situation B: groups\n  - G94: Short text alternative using one technique "
                      "from each group\n  - Group one\n    - H37: Using alt attributes", sc)
        self.assertIn("- Marking sequences **AND** G57: Ordering the content (see note) "
                      "using one of:\n  - C6: Positioning content", sc)
        self.assertIn("- G10: Creating components\n  - All of:\n    - ARIA5: Using a role", sc)
        self.assertIn("## Failures\n\n- F59: ", sc)
        self.assertNotIn("ARIA4", sc)  # advisory techniques are dropped

    def test_two_runs_are_byte_identical(self):
        other = self.tmp / "other" / "wcag"
        self.generate()
        r = self.update(out=other)
        self.assertEqual(r.returncode, 0, r.stderr)
        a, b = snapshot(self.out), snapshot(other)
        self.assertEqual(a.keys(), b.keys())
        for k in a:
            if k.endswith(".md"):
                self.assertEqual(a[k], b[k], k)
        ma, mb = json.loads(a["manifest.json"]), json.loads(b["manifest.json"])
        ma.pop("fetched_at"), mb.pop("fetched_at")
        self.assertEqual(ma, mb)

    def test_update_reports_diff(self):
        r = self.update()
        self.assertIn("2 criteria (A 1, AA 0, AAA 0, obsolete 1)", r.stdout)
        self.assertIn("added: 4.1.2 Name, Role, Value (A)", r.stdout)
        data = mini()
        criteria(data)[1]["content"] += "<p>Errata.</p>"
        r = self.update(self.write_source(data))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("changed: 4.1.2 Name, Role, Value (A)", r.stdout)
        self.assertIn("review the matching sections", r.stdout)

    def test_version_setting_changes_output(self):
        r = self.update(MINI, "--version", "21")
        self.assertEqual(r.returncode, 0, r.stderr)
        m = json.loads((self.out / "manifest.json").read_text())
        self.assertEqual(m["wcag_version"], "2.1")
        self.assertIn("https://www.w3.org/TR/WCAG21/#dfn-name", self.sc())

    def test_regeneration_preserves_guidance(self):
        self.generate()
        checks = self.refs / "checks.md"
        checks.write_bytes(b"# Checks\n\n## 4.1.2 Name, Role, Value\n\nhand-written\n")
        before = checks.read_bytes()
        self.generate()
        self.assertEqual(checks.read_bytes(), before)


class BadSourceTest(Base):
    def setUp(self):
        super().setUp()
        self.generate()
        self.before = snapshot(self.out)

    def assertRejected(self, source, needle):
        r = self.update(source)
        self.assertEqual(r.returncode, 2, r.stdout + r.stderr)
        self.assertIn(needle, r.stderr)
        self.assertNotIn("Traceback", r.stderr)
        self.assertIn("left unchanged", r.stderr)
        self.assertEqual(snapshot(self.out), self.before)
        self.assertEqual([p.name for p in self.refs.iterdir()], ["wcag"])

    def test_missing_guidelines(self):
        self.assertRejected(BAD, "guidelines")

    def test_not_json(self):
        p = self.tmp / "x.json"
        p.write_text("<html>not json</html>")
        self.assertRejected(p, "not valid JSON")

    def mutate(self, fn):
        data = mini()
        fn(criteria(data))
        return self.write_source(data)

    def test_missing_level(self):
        self.assertRejected(self.mutate(lambda c: c[1].pop("level")), "missing 'level'")

    def test_unknown_level(self):
        self.assertRejected(self.mutate(lambda c: c[1].update(level="AA+")),
                            "unknown level 'AA+'")

    def test_bad_num(self):
        self.assertRejected(self.mutate(lambda c: c[1].update(num="4.1")), "bad num '4.1'")

    def test_bad_id(self):
        self.assertRejected(self.mutate(lambda c: c[1].update(id="../../escape")), "bad id")

    def test_duplicate_num(self):
        self.assertRejected(self.mutate(lambda c: c[0].update(num="4.1.2")),
                            "duplicate criterion 4.1.2")

    def test_non_string_versions(self):
        self.assertRejected(self.mutate(lambda c: c[1].update(versions=[2.2])),
                            "'versions' must be strings")

    def test_odd_field_type_is_reported_not_raised(self):
        def odd(c):
            c[1]["techniques"]["sufficient"][0]["groups"] = ["not a dict"]
        self.assertRejected(self.mutate(odd), "unexpected content")


class SwapFailureTest(Base):
    def test_failed_swap_restores_old_tree(self):
        self.generate()
        before = snapshot(self.out)
        real = os.rename
        calls = []

        def flaky(src, dst):
            calls.append((src, dst))
            if len(calls) == 2:  # the new tree moving into place
                raise OSError("simulated rename failure")
            return real(src, dst)

        err = io.StringIO()
        with mock.patch.object(wcag.os, "rename", flaky), contextlib.redirect_stderr(err), \
                contextlib.redirect_stdout(io.StringIO()):
            rc = wcag.main(["update", "--source", str(MINI), "--out", str(self.out)])
        self.assertEqual(rc, 2)
        self.assertIn("simulated rename failure", err.getvalue())
        self.assertEqual(snapshot(self.out), before)
        self.assertEqual([p.name for p in self.refs.iterdir()], ["wcag"])

    def test_invalid_generated_tree_aborts(self):
        self.generate()
        before = snapshot(self.out)
        with mock.patch.object(wcag, "validate_tree", side_effect=wcag.SourceError("bad tree")), \
                contextlib.redirect_stderr(io.StringIO()), contextlib.redirect_stdout(io.StringIO()):
            rc = wcag.main(["update", "--source", str(MINI), "--out", str(self.out)])
        self.assertEqual(rc, 2)
        self.assertEqual(snapshot(self.out), before)
        self.assertEqual([p.name for p in self.refs.iterdir()], ["wcag"])


class DryRunTest(Base):
    def test_changed_criterion_listed_and_nothing_written(self):
        self.generate()
        before = snapshot(self.out)
        data = mini()
        criteria(data)[1]["content"] = criteria(data)[1]["content"].replace(
            "form elements", "form fields")
        r = self.update(self.write_source(data), "--dry-run")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("changed: 1", r.stdout)
        self.assertIn("changed: 4.1.2 Name, Role, Value (A)", r.stdout)
        self.assertNotIn("4.1.1", r.stdout)
        self.assertEqual(snapshot(self.out), before)

    def test_added_and_removed(self):
        self.generate()
        data = mini()
        crit = criteria(data)
        new = dict(crit[1], id="status-messages", num="4.1.3", handle="Status Messages", level="AA")
        crit[:] = [crit[1], new]
        r = self.update(self.write_source(data), "--dry-run")
        self.assertIn("added: 4.1.3 Status Messages (AA)", r.stdout)
        self.assertIn("removed: 4.1.1", r.stdout)

    def test_unchanged_source_is_up_to_date(self):
        self.generate()
        before = snapshot(self.out)
        r = self.update(MINI, "--dry-run")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("up to date", r.stdout)
        self.assertEqual(snapshot(self.out), before)

    def test_version_change_is_not_up_to_date(self):
        self.generate()
        r = self.update(MINI, "--dry-run", "--version", "21")
        self.assertNotIn("up to date", r.stdout)
        self.assertIn("changed: 2", r.stdout)


class CheckTest(Base):
    def setUp(self):
        super().setUp()
        self.generate()

    def assertFails(self, needle):
        r = self.check()
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn(needle, r.stdout + r.stderr)
        return r

    def rehash(self, rel):
        mf = self.out / "manifest.json"
        m = json.loads(mf.read_text())
        m["files"][rel] = wcag.sha256((self.out / rel).read_bytes())
        mf.write_text(json.dumps(m))

    def test_clean_tree_passes(self):
        (self.refs / "checks.md").write_text(
            "# Checks\n\n## 4.1.2 Name, Role, Value\n\nSee also SC 4.1.2 and 4.1.2 Name, Role, "
            "Value. Ratios like 4.5:1 and versions 2.2 are not citations.\n")
        (self.refs / "audit.md").write_text(
            "# Audit\n\n- SC 4.1.2 Name, Role, Value\n| x | 4.1.2 Name, Role, Value |\n")
        r = self.check()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("ok:", r.stdout)

    def test_crlf_checkout_passes(self):
        for f in (self.out / "sc").glob("*.md"):
            f.write_bytes(f.read_bytes().replace(b"\n", b"\r\n"))
        r = self.check()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_hand_edited_sc_file_fails(self):
        f = self.out / "sc/4.1.2-name-role-value.md"
        f.write_text(f.read_text() + "\nextra\n")
        r = self.assertFails("4.1.2-name-role-value.md")
        self.assertIn("edited by hand", r.stdout)
        self.assertIn("wcag.py update", r.stdout)

    def test_orphan_sc_file_fails(self):
        (self.out / "sc/9.9.9-made-up.md").write_text("# 9.9.9 Made Up\n")
        r = self.assertFails("9.9.9-made-up.md")
        self.assertIn("orphan criterion file not in index", r.stdout)
        self.assertIn("not generated (absent from manifest.json)", r.stdout)

    def test_missing_sc_file_fails(self):
        (self.out / "sc/4.1.2-name-role-value.md").unlink()
        r = self.assertFails("missing generated file")
        self.assertIn("index row 4.1.2 points to missing file", r.stdout)

    def test_heading_disagreeing_with_index_fails(self):
        f = self.out / "sc/4.1.2-name-role-value.md"
        f.write_text(f.read_text().replace("# 4.1.2 ", "# 4.1.9 ", 1))
        self.rehash("sc/4.1.2-name-role-value.md")
        self.assertFails("heading does not match index row 4.1.2")

    def test_unreadable_manifest_fails(self):
        (self.out / "manifest.json").write_text("{not json")
        r = self.assertFails("cannot read")
        self.assertIn("run scripts/wcag.py update", r.stderr)

    def test_obsolete_section_in_checks_fails(self):
        (self.refs / "checks.md").write_text("# Checks\n\n## 4.1.1 Parsing\n\ntext\n")
        r = self.assertFails("cites 4.1.1, which is obsolete")
        self.assertIn("checks.md:3", r.stdout)

    def test_unknown_section_in_checks_fails(self):
        (self.refs / "checks.md").write_text("# Checks\n\n## 9.9.9 Made Up\n\ntext\n")
        self.assertFails("cites 9.9.9, which is not in the index")

    def test_unknown_inline_citation_in_audit_fails(self):
        (self.refs / "audit.md").write_text("# Audit\n\n## Manual\n\n- SC 9.9.8 Nope\n")
        self.assertFails("audit.md:5 (section 'Manual') cites 9.9.8")

    def test_bare_citation_is_checked(self):
        (self.refs / "audit.md").write_text("# Audit\n\n| keyboard | 9.9.7 Made Up |\n"
                                            "a 4.1.1 finding\n")
        r = self.assertFails("cites 9.9.7, which is not in the index")
        self.assertIn("cites 4.1.1, which is obsolete", r.stdout)

    def test_citation_name_mismatch_fails(self):
        (self.refs / "audit.md").write_text("# Audit\n\n- SC 4.1.2 Name Role Thing\n")
        self.assertFails("name after 4.1.2 does not match the index name 'Name, Role, Value'")

    def test_heading_name_mismatch_fails(self):
        (self.refs / "checks.md").write_text("# Checks\n\n## 4.1.2 Name Role Value\n")
        r = self.assertFails("does not match the index name 'Name, Role, Value'")
        self.assertEqual(r.stdout.count("FAIL"), 1)  # the heading is reported once


class IndexTest(unittest.TestCase):
    def test_pipe_in_handle_round_trips(self):
        row = (f"| 1.2.3 | {wcag.cell('A | B')} | AA | 2.2 |  | "
               "[sc/1.2.3-x.md](sc/1.2.3-x.md) |")
        self.assertEqual(wcag.parse_index(row)["1.2.3"]["handle"], "A | B")


